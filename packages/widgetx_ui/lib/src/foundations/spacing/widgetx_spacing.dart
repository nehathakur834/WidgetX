/// Spacing scale for WidgetX UI.
///
/// Use these constants instead of hardcoded pixel values to ensure
/// consistent spacing across all components.
abstract final class WidgetXSpacing {
  /// 2px — hairline gap, rarely used directly.
  static const double xxs = 2;

  /// 4px — tight internal padding.
  static const double xs = 4;

  /// 8px — default small padding / gap.
  static const double sm = 8;

  /// 16px — default medium padding.
  static const double md = 16;

  /// 24px — large padding.
  static const double lg = 24;

  /// 32px — extra-large padding or section gap.
  static const double xl = 32;

  /// 48px — prominent section spacing.
  static const double xxl = 48;

  /// 64px — page-level vertical rhythm.
  static const double xxxl = 64;
}
